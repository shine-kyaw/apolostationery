/* ==========================================================================
   APOLO — translation check
   --------------------------------------------------------------------------
     node tools/check-i18n.mjs            check; exits 1 if anything is broken
     node tools/check-i18n.mjs --table    also write docs/TRANSLATIONS.md, a
                                          Key | English | Burmese table for
                                          whoever is proofreading the Burmese

   Errors (exit 1):
     · a key the site uses that the English table does not have
     · an English key with no Burmese (or an empty one)
     · {placeholders} that differ between the two languages
   Warnings:
     · English keys nothing uses any more
     · Burmese keys with no English twin (opt./val./unit. are allowed)
   ========================================================================== */

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const EN = (await import(pathToFileURL(join(ROOT, 'js/i18n/en.js')))).default;
const MY = (await import(pathToFileURL(join(ROOT, 'js/i18n/my.js')))).default;
const MY_ONLY = /^(opt|val|unit)\./;

/* ---- what the code asks for ---- */
async function walk(dir, out = []) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    if (['node_modules', '.git', 'data', 'docs', 'img', '_research', 'i18n'].includes(e.name)) continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) await walk(p, out);
    else if (/\.(js|mjs|html)$/.test(e.name)) out.push(p);
  }
  return out;
}

const used = new Map();          // key → [files]
const prefixes = new Set();      // dynamic keys like sort.${k}
const note = (key, file) => { if (!used.has(key)) used.set(key, []); used.get(key).push(file); };

for (const file of await walk(ROOT)) {
  const rel = relative(ROOT, file).replace(/\\/g, '/');
  if (rel === 'js/i18n.js' || rel.startsWith('tools/check-i18n')) continue;   // they only mention keys in comments
  const src = await readFile(file, 'utf8');
  for (const m of src.matchAll(/\b(?:t|tr)\(\s*(['"`])([\w.\-& ]+?)\1/g)) note(m[2], rel);
  for (const m of src.matchAll(/\b(?:t|tr)\(\s*`([\w.\-]+)\$\{/g)) prefixes.add(m[1]);
  for (const m of src.matchAll(/data-i18n(?:-html)?="([\w.\-]+)"/g)) note(m[1], rel);
  for (const m of src.matchAll(/data-[\w-]*-key="([\w.\-]+)"/g)) note(m[1], rel);   // e.g. data-title-key
  for (const m of src.matchAll(/data-i18n-attr="([^"]+)"/g))
    for (const pair of m[1].split(';')) { const k = pair.split(':')[1]?.trim(); if (k) note(k, rel); }
}

/* ---- compare ---- */
const errors = [], warns = [];
const dyn = k => [...prefixes].some(p => k.startsWith(p));
const holes = s => [...String(s).matchAll(/\{(\w+)\}/g)].map(m => m[1]).sort().join(',');

for (const [k, files] of used)
  if (!(k in EN) && !MY_ONLY.test(k)) errors.push(`used but not in English table: ${k}  (${[...new Set(files)].join(', ')})`);

for (const k of Object.keys(EN)) {
  if (!(k in MY)) errors.push(`no Burmese for: ${k}`);
  else if (!String(MY[k]).trim()) errors.push(`empty Burmese for: ${k}`);
  else if (holes(EN[k]) !== holes(MY[k])) errors.push(`placeholders differ for ${k}: English {${holes(EN[k])}} vs Burmese {${holes(MY[k])}}`);
  if (!used.has(k) && !dyn(k)) warns.push(`English key not used anywhere: ${k}`);
}
for (const k of Object.keys(MY))
  if (!(k in EN) && !MY_ONLY.test(k)) warns.push(`Burmese key with no English: ${k}`);

console.log(`${Object.keys(EN).length} English keys, ${Object.keys(MY).length} Burmese keys, ${used.size} used in code`);
for (const w of warns) console.log('  warn  ' + w);
for (const e of errors) console.log('  ERROR ' + e);
console.log(errors.length ? `✗ ${errors.length} problem(s)` : '✓ translations are complete');

/* ---- the proofreading table ---- */
if (process.argv.includes('--table')) {
  const cell = s => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ').replace(/</g, '&lt;');
  const rows = [...new Set([...Object.keys(EN), ...Object.keys(MY)])];
  const out = [
    '# APOLO — translation table', '',
    '_Generated by `node tools/check-i18n.mjs --table`. Edit the files in `js/i18n/en/` and `js/i18n/my/`, not this page._', '',
    'Text in `{curly}` braces is filled in by the site (a number, a price) — keep it exactly as is.',
    'Text in `&lt;tags&gt;` is a link or emphasis — keep the tags, translate the words between them.', '',
    '| Key | English | Burmese |', '|---|---|---|',
    ...rows.map(k => `| \`${k}\` | ${cell(EN[k])} | ${cell(MY[k])} |`), ''
  ];
  await writeFile(join(ROOT, 'docs/TRANSLATIONS.md'), out.join('\n'));
  console.log(`wrote docs/TRANSLATIONS.md (${rows.length} rows)`);
}
process.exit(errors.length ? 1 : 0);
